"""Licensed desktop handoff and validation gates, not simulated desktop checks."""
import hashlib
import json
import shutil
import os
import tempfile
import uuid
from pathlib import Path
from typing import Literal

from pydantic import Field
from pypdf import PdfReader

from .models import CANVAS, EngineError, StrictModel


def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


class NativeReceipt(StrictModel):
    bundle_id: uuid.UUID
    side: Literal["front", "back"]
    source_eps_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    profile_sha256: str | None = Field(default=None, pattern=r"^[a-f0-9]{64}$")
    application: Literal["Illustrator"]
    version: str = Field(min_length=1, max_length=100)
    saved_using: Literal["IllustratorSaveOptions"]
    reopened: Literal[True]
    width_points: float
    height_points: float
    color_mode: Literal["CMYK"]
    path_items: int = Field(gt=0)
    raster_items: Literal[0]
    placed_items: Literal[0]
    live_text_items: Literal[0]
    non_cmyk_path_items: Literal[0]
    profile_assignment_operator_confirmed: bool = False
    file_bytes: int = Field(gt=0, le=60 * 1024 * 1024)


def prepare_desktop(output: Path, profile: Path | None = None) -> dict:
    from .pipeline import atomic_json
    destination = output / "desktop"
    target = destination / "request.json"
    sources = {side: sha256(output / f"{side}-body.eps") for side in ("front", "back")}
    profile_hash = sha256(profile) if profile else None
    if target.exists():
        existing = json.loads(target.read_text())
        if existing["eps_sha256"] != sources or existing["profile_sha256"] != profile_hash:
            raise EngineError("DESKTOP_PACKAGE_STALE", "Desktop package no longer matches these EPS files or printer profile.")
        return existing
    destination.mkdir(exist_ok=True)
    from .exporters import ColorConverter
    profile_report = ColorConverter(profile).profile_info if profile else None
    request = {
        "bundle_id": str(uuid.uuid4()), "eps_sha256": sources,
        "profile_sha256": profile_hash, "profile_description": profile_report["description"] if profile_report else None,
        "canvas": CANVAS.model_dump(), "required_applications": ["Illustrator"],
        "status": "native_export_not_run", "production_validation_in_scope": False,
        "evidence_trust": "Authenticated operator-submitted desktop results, not remote cryptographic attestation.",
    }
    template = Path(__file__).with_name("desktop_templates") / "illustrator-export.jsx"
    for side in ("front", "back"):
        (destination / f"export-{side}.jsx").write_text(
            template.read_text().replace("__REQUEST__", json.dumps({**request, "side": side}, ensure_ascii=True)),
            encoding="utf-8",
        )
    if profile:
        shutil.copyfile(profile, destination / "printer-profile.icc")
    (destination / "NATIVE-EXPORT.md").write_text(
        "# Native AI export handoff (not production approval)\n\n"
        "ICC is optional. With no supplied ICC, preserve unmanaged DeviceCMYK numbers; "
        "no printer color matching is claimed. Do not assign a random printer profile. "
        "Open the matching EPS and run its export-front.jsx/export-back.jsx in Illustrator. "
        "Return each AI plus its receipt through native-import CLI or the native API.\n"
        "If an ICC is bundled, assign that exact profile while preserving CMYK numbers.\n"
        "Production approval, printer proofing and the two-application validation matrix "
        "are not part of this engine phase. The script uses IllustratorSaveOptions, targets CS6, "
        "reopens the file and checks physical size, CMYK and real paths without images or live fonts. "
        "Existing AI files are never overwritten. Actual Illustrator execution still requires a licensed desktop.\n",
        encoding="utf-8",
    )
    atomic_json(target, request)
    return request


def inspect_native_ai(path: Path) -> dict:
    """Reject ordinary PDF/EPS renamed .ai; inspect PDF-compatible native structure."""
    if path.stat().st_size > 60 * 1024 * 1024:
        raise EngineError("AI_TOO_LARGE", "AI import exceeds 60 MiB.")
    try:
        with path.open("rb") as source:
            if source.read(5) != b"%PDF-":
                raise ValueError("Expected the PDF-compatible native AI generated by the handoff.")
            source.seek(0)
            pdf = PdfReader(source, strict=True)
            if pdf.is_encrypted or len(pdf.pages) != 1:
                raise ValueError("AI must have one unencrypted page.")
            piece = pdf.trailer["/Root"].get("/PieceInfo")
            if not piece:
                raise ValueError("Missing Illustrator private editing data.")
            illustrator = piece.get_object().get("/Illustrator")
            if not illustrator or not illustrator.get_object().get("/Private"):
                raise ValueError("Missing Illustrator private editing data.")
            page = pdf.pages[0]
            if abs(float(page.mediabox.width) - 1584) > 0.05 or abs(float(page.mediabox.height) - 2232) > 0.05:
                raise ValueError("Native AI page does not match 22 x 31 inches.")
            seen = set()
            def inspect_resources(resources, depth=0):
                if depth > 12 or len(seen) > 1000:
                    raise ValueError("AI resource complexity exceeds safety limit.")
                for item in resources.get("/XObject", {}).get_object().values() if "/XObject" in resources else ():
                    obj = item.get_object()
                    if id(obj) in seen:
                        continue
                    seen.add(id(obj))
                    if obj.get("/Subtype") == "/Image":
                        raise ValueError("AI contains an embedded raster image.")
                    if obj.get("/Subtype") == "/Form":
                        inspect_resources(obj.get("/Resources", {}), depth + 1)
            inspect_resources(page.get("/Resources", {}).get_object() if "/Resources" in page else {})
            return {"pdf_compatible": True, "illustrator_private_data_present": True, "pages": 1, "embedded_pdf_image_count": 0}
    except EngineError:
        raise
    except Exception as exc:
        raise EngineError("INVALID_NATIVE_AI", f"Native AI structural check failed: {exc}") from exc


def import_native(output: Path, side: str, source: Path, receipt: NativeReceipt) -> dict:
    from .pipeline import atomic_json
    manifest = json.loads((output / "manifest.json").read_text())
    if manifest["status"] not in ("awaiting_desktop", "review_required"):
        raise EngineError("JOB_NOT_IMPORTABLE", "Only completed, unapproved jobs accept desktop results.")
    request = json.loads((output / "desktop/request.json").read_text())
    try:
        major = int(receipt.version.split(".")[0])
        if major < 16:
            raise ValueError("Illustrator CS6 or later is required.")
    except ValueError as exc:
        raise EngineError("INVALID_APPLICATION_VERSION", "Receipt must include the actual numeric Illustrator version, CS6 or later.") from exc
    if "ai" not in manifest["formats"]:
        raise EngineError("AI_NOT_REQUESTED", "Create a job requesting native AI handoff before importing AI.")
    if (
        receipt.side != side or str(receipt.bundle_id) != request["bundle_id"]
        or receipt.source_eps_sha256 != request["eps_sha256"][side]
        or sha256(output / f"{side}-body.eps") != receipt.source_eps_sha256
        or receipt.profile_sha256 != request["profile_sha256"]
        or (request["profile_sha256"] is not None and not receipt.profile_assignment_operator_confirmed)
        or source.stat().st_size != receipt.file_bytes
        or abs(receipt.width_points - 1584) > 0.05 or abs(receipt.height_points - 2232) > 0.05
    ):
        raise EngineError("DESKTOP_RECEIPT_MISMATCH", "Receipt does not match this side, bundle, profile, source EPS or canvas.")
    structure = inspect_native_ai(source)
    destination = output / f"{side}-body.ai"
    if destination.exists():
        raise EngineError("AI_ALREADY_IMPORTED", "An AI output already exists. Start a new job rather than replacing approved evidence.")
    # Publish complete files atomically, without replacing an existing output.
    with tempfile.NamedTemporaryFile(dir=output, suffix=".incoming", delete=False) as stream:
        temporary = Path(stream.name)
    try:
        shutil.copyfile(source, temporary)
        try:
            os.link(temporary, destination)
        except FileExistsError as exc:
            raise EngineError("AI_ALREADY_IMPORTED", "AI output already exists; it will not be replaced.") from exc
    finally:
        temporary.unlink(missing_ok=True)
    report = {**receipt.model_dump(mode="json"), "sha256": sha256(destination), "structure": structure}
    manifest["panels"][side]["native_ai"] = report
    manifest["panels"][side]["exports"].append(destination.name)
    if all(p.get("native_ai") for p in manifest["panels"].values()):
        manifest["status"] = "review_required"
        manifest["preflight"]["native_ai_status"] = "desktop_saved_and_returned"
    atomic_json(output / "manifest.json", manifest)
    return manifest
